export function getDisciplinaVisualTheme(disciplinaOuSlug?: string | null): DisciplinaVisualTheme {
  if (!disciplinaOuSlug) return TEMAS_DISCIPLINAS.administrativo;
  const s = String(disciplinaOuSlug).toLowerCase().replace(/[^a-z0-9-]/g, '-');

  // Mapeamentos precisos de áreas e sub-áreas
  if (s.includes('process') && s.includes('penal')) return TEMAS_DISCIPLINAS['processual-penal'];
  if (s.includes('process') && (s.includes('trab') || s.includes('trabalhista'))) return TEMAS_DISCIPLINAS['processual-trabalho'];
  if (s.includes('process') && s.includes('civil')) return TEMAS_DISCIPLINAS['processual-civil'];
  if (s.includes('lei-penal') || s.includes('legislacao-penal')) return TEMAS_DISCIPLINAS['lei-penal-especial'];
  if (s.includes('penal')) return TEMAS_DISCIPLINAS.penal;
  if (s.includes('admin')) return TEMAS_DISCIPLINAS.administrativo;
  if (s.includes('const')) return TEMAS_DISCIPLINAS.constitucional;
  if (s.includes('trab')) return TEMAS_DISCIPLINAS.trabalho;
  if (s.includes('civil')) return TEMAS_DISCIPLINAS.civil;
  if (s.includes('tribut')) return TEMAS_DISCIPLINAS.tributario;
  if (s.includes('empres')) return TEMAS_DISCIPLINAS.empresarial;
  if (s.includes('ambien')) return TEMAS_DISCIPLINAS.ambiental;
  if (s.includes('previd')) return TEMAS_DISCIPLINAS.previdenciario;
  if (s.includes('finan')) return TEMAS_DISCIPLINAS.financeiro;
  if (s.includes('internac')) return TEMAS_DISCIPLINAS['internacional-privado'];
  if (s.includes('urban')) return TEMAS_DISCIPLINAS.urbanistico;
  if (s.includes('human')) return TEMAS_DISCIPLINAS['direitos-humanos'];
  if (s.includes('filoso') || s.includes('teoria')) return TEMAS_DISCIPLINAS.filosofia;
  if (s.includes('desport')) return TEMAS_DISCIPLINAS.desportivo;
  if (s.includes('politic')) return TEMAS_DISCIPLINAS['politicas-publicas'];
  if (s.includes('portug')) return TEMAS_DISCIPLINAS.portugues;
  if (s.includes('complem') || s.includes('formacao')) return TEMAS_DISCIPLINAS['formacao-complementar'];

  return TEMAS_DISCIPLINAS[s] || TEMAS_DISCIPLINAS.administrativo;
}
