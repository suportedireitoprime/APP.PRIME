export function getTituloCurado(item: { numero: number; titulo: string }): AulaTituloCurado {
  const curado = TITULOS_INICIANTES[item.numero];
  if (curado) return curado;
  
  const partes = item.titulo.split(/\s*[-–—:]\s*/);
  return {
    titulo: partes[0]?.trim() || item.titulo,
    descricao: partes[1]?.trim() || 'Fundamentos e prática jurídica.',
  };
}
